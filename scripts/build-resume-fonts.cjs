// Copies the open fonts the resume templates use from @fontsource into public/resume-templates/fonts
// and writes css/fonts.css. The Resume page preview and the server's PDF printing both load these
// same files, so previews and downloaded PDFs use identical fonts and break lines identically.
// Run after changing the font list: node scripts/build-resume-fonts.cjs
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const templateRoot = path.join(root, 'public', 'resume-templates');
const fontOutput = path.join(templateRoot, 'fonts');

// Each template font token starts with one of these names (see css/base.css). Microsoft's fonts
// cannot be redistributed, so each maps to an open font: metric-compatible where one exists
// (Arimo, Tinos, Carlito, Caladea, Gelasio), otherwise the closest open design.
const families = [
  { name: 'QTS Arial', fontPackage: 'arimo' },
  { name: 'QTS Arial Black', fontPackage: 'archivo-black', anyWeight: true },
  { name: 'QTS Times', fontPackage: 'tinos' },
  { name: 'QTS Calibri', fontPackage: 'carlito' },
  { name: 'QTS Cambria', fontPackage: 'caladea' },
  { name: 'QTS Georgia', fontPackage: 'gelasio' },
  { name: 'QTS Palatino', fontPackage: 'gelasio' },
  { name: 'QTS Verdana', fontPackage: 'dejavu-sans' },
  { name: 'QTS Tahoma', fontPackage: 'dejavu-sans' },
  { name: 'QTS Trebuchet', fontPackage: 'fira-sans' },
  { name: 'QTS Mono', fontPackage: 'inconsolata' },
];
const styleFiles = ['400.css', '400-italic.css', '700.css', '700-italic.css'];

fs.rmSync(fontOutput, { recursive: true, force: true });
const rules = [];
const copied = new Set();
for (const { name, fontPackage, anyWeight } of families) {
  const packageRoot = path.join(root, 'node_modules', '@fontsource', fontPackage);
  for (const styleFile of styleFiles) {
    const stylePath = path.join(packageRoot, styleFile);
    if (!fs.existsSync(stylePath)) continue;
    const css = fs.readFileSync(stylePath, 'utf8');
    for (const [, block] of css.matchAll(/@font-face\s*\{([^}]*)\}/g)) {
      const file = /url\(\.\/files\/([a-z0-9-]+\.woff2)\)/.exec(block)?.[1];
      const style = /font-style:\s*(\w+)/.exec(block)?.[1];
      const weight = /font-weight:\s*(\d+)/.exec(block)?.[1];
      const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
      if (!file || !style || !weight) throw new Error(`Unexpected @font-face in ${stylePath}`);
      const target = path.join(fontOutput, fontPackage, file);
      if (!copied.has(target)) {
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.copyFileSync(path.join(packageRoot, 'files', file), target);
        copied.add(target);
      }
      rules.push([
        '@font-face {',
        `  font-family: ${JSON.stringify(name)};`,
        `  font-style: ${style};`,
        // A single-weight display face serves every requested weight instead of being faux-bolded.
        `  font-weight: ${anyWeight ? '100 900' : weight};`,
        '  font-display: block;',
        `  src: url(/resume-templates/fonts/${fontPackage}/${file}) format("woff2");`,
        range ? `  unicode-range: ${range.trim()};` : null,
        '}',
      ].filter(Boolean).join('\n'));
    }
  }
  const license = path.join(packageRoot, 'LICENSE');
  if (fs.existsSync(license)) fs.copyFileSync(license, path.join(fontOutput, fontPackage, 'LICENSE'));
}

fs.writeFileSync(
  path.join(templateRoot, 'css', 'fonts.css'),
  `/* Generated by scripts/build-resume-fonts.cjs; do not edit. Open fonts shared by the Resume page\n   preview and Generation PDF printing. Licenses: fonts/<family>/LICENSE. */\n\n${rules.join('\n\n')}\n`,
);
console.log(`${rules.length} @font-face rules, ${copied.size} font files`);
